void interrupt_handler(struct trapframe *tf) {
    // 去掉最高位的中断标志，保留原因编号；不修改保存的现场。
    uintptr_t cause = tf->cause & ~((uintptr_t)1 << (sizeof(uintptr_t) * 8 - 1));

    switch (cause) {
        case IRQ_U_SOFT:
            cprintf("User software interrupt\n");
            break;
        case IRQ_S_SOFT:
            cprintf("Supervisor software interrupt\n");
            break;
        case IRQ_M_SOFT:
            cprintf("Machine software interrupt\n");
            break;
        case IRQ_U_TIMER:
            cprintf("User timer interrupt\n");
            break;
        case IRQ_S_TIMER:
            // 重新安排定时事件，才能持续收到时钟中断。
            clock_set_next_event();
            ticks++;
            if (ticks % TICK_NUM == 0) {
                print_ticks();
                // ticks / TICK_NUM 就是累计打印次数。
                if (ticks / TICK_NUM >= SHUTDOWN_AFTER) {
                    sbi_shutdown();
                }
            }
            break;
        case IRQ_M_TIMER:
            cprintf("Machine timer interrupt\n");
            break;
        case IRQ_U_EXT:
            cprintf("User external interrupt\n");
            break;
        case IRQ_S_EXT:
            cprintf("Supervisor external interrupt\n");
            break;
        case IRQ_M_EXT:
            cprintf("Machine external interrupt\n");
            break;
        default:
            cprintf("Unknown interrupt: cause %lu\n", (unsigned long)cause);
            print_trapframe(tf);
            break;
    }
}

void exception_handler(struct trapframe *tf) {
    switch (tf->cause) {
        case CAUSE_ILLEGAL_INSTRUCTION:
            cprintf("Illegal instruction at %p\n", tf->epc);
            break;
        case CAUSE_BREAKPOINT:
            cprintf("Breakpoint at %p\n", tf->epc);
            break;
        default:
            // 未要求恢复的异常只输出现场，不擅自跳过指令。
            print_trapframe(tf);
            return;
    }

    // 当前实现处理 16/32 位指令，覆盖现有测试；指导书未限定指令长度。
    // 低两位不是 11 表示 16 位指令；此处其余情况按 32 位处理，未解码更长编码。
    uint16_t instruction = *(const uint16_t *)tf->epc;
    tf->epc += (instruction & 0x3) == 0x3 ? 4 : 2;
}

/*
第 63 位                 第 62～0 位
┌────────────┬────────────────────────┐
│ 1：中断     │ 具体原因编号            │
│ 0：异常     │                        │
└────────────┴────────────────────────┘
*/
static inline void trap_dispatch(struct trapframe *tf) {
    if ((intptr_t)tf->cause < 0) {
        // interrupts
        interrupt_handler(tf);
    } else {
        // exceptions
        exception_handler(tf);
    }
}

/* *
 * trap - handles or dispatches an exception/interrupt. if and when trap()
 * returns,
 * the code in kern/trap/trapentry.S restores the old CPU state saved in the
 * trapframe and then uses the iret instruction to return from the exception.
 * */
void trap(struct trapframe *tf) {
    // dispatch based on what type of trap occurred
    trap_dispatch(tf);
}
